// Scans the negative control page and checks that every planted problem is
// found in the right bucket and nothing unexpected shows up.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { scan } from './scan.mjs';
import { bucketOf } from './report.mjs';

const FIXTURE = fileURLToPath(new URL('../test/fixtures/negative-control.html', import.meta.url));
const EXPECTED = fileURLToPath(new URL('../test/fixtures/expected.json', import.meta.url));

function observedRuleSets(report) {
  const observed = {};
  for (const r of report.results) {
    if (!r.ok) continue;
    for (const f of r.findings) ((observed[f.source] ||= {})[bucketOf(f)] ||= new Set()).add(f.id);
  }
  const plain = {};
  for (const [src, buckets] of Object.entries(observed)) {
    plain[src] = {};
    for (const [b, set] of Object.entries(buckets)) plain[src][b] = [...set].sort();
  }
  return plain;
}

/** @returns {Promise<{ok: boolean, problems: string[], axeCore: string}>} */
export async function selfTest({ update = false } = {}) {
  const report = await scan([pathToFileURL(FIXTURE).href], { mode: 'full', concurrency: 1 });
  const first = report.results[0];
  const axeCore = report.manifest.engine.axeCore;
  if (!first?.ok) return { ok: false, problems: [`fixture did not load: ${first?.error}`], axeCore };

  const plain = observedRuleSets(report);
  if (update) {
    await writeFile(EXPECTED, `${JSON.stringify({
      note: 'Generated by `floorcheck --self-test --update-expected` from a real scan of negative-control.html.',
      axeCore,
      expected: plain,
    }, null, 2)}\n`);
    return { ok: true, problems: [], axeCore, updated: true };
  }

  const baseline = JSON.parse(await readFile(EXPECTED, 'utf8'));
  const problems = [];
  if (baseline.axeCore !== axeCore) {
    problems.push(`axe-core is ${axeCore}, the baseline was made with ${baseline.axeCore}. Review the diff and regenerate.`);
  }
  const exp = baseline.expected || {};
  for (const src of new Set([...Object.keys(exp), ...Object.keys(plain)])) {
    for (const b of new Set([...Object.keys(exp[src] || {}), ...Object.keys(plain[src] || {})])) {
      const want = new Set(exp[src]?.[b] || []);
      const got = new Set(plain[src]?.[b] || []);
      const missing = [...want].filter((x) => !got.has(x));
      const extra = [...got].filter((x) => !want.has(x));
      if (missing.length) problems.push(`${src}/${b} missing: ${missing.join(', ')} (a check stopped working)`);
      if (extra.length) problems.push(`${src}/${b} unexpected: ${extra.join(', ')} (a filter leaked or a new rule appeared)`);
    }
  }
  return { ok: problems.length === 0, problems, axeCore };
}
